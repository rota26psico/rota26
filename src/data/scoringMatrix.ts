/* ── Parsing e estrutura final ─────────────────────────────────────────── */

const parse = <K extends string>(s: string): Partial<Record<K, number>> =>
  Object.fromEntries(s.split(/\s+/).filter(Boolean).map(t => {
    const m = t.match(/^([A-Z_]+)(\d)$/);
    if (!m) throw new Error(`Token inválido na matriz de pontuação: "${t}"`);
    return [m[1], Number(m[2])];
  })) as Partial<Record<K, number>>;

export interface LinhaMatriz {
  questaoId: string;
  alternativaId: string;
  texto: string;
  peso: number;
  tipo: string;
  contexto: string;
  jung: PoloJung;
  eixo: EixoAux;
  capacidades: Partial<Record<Capacidade, number>>;
  belbin: Partial<Record<PapelBelbin, number>>;
}

/** A matriz completa e auditável — uma linha por alternativa. */
export const MATRIZ_PONTUACAO: LinhaMatriz[] = QUESTOES.flatMap(q =>
  q.alternativas.map(a => {
    const par = M[a.id];
    if (!par) throw new Error(`Alternativa ${a.id} sem linha na matriz de pontuação.`);
    return {
      questaoId: q.id, alternativaId: a.id, texto: a.texto, peso: q.peso,
      tipo: q.tipo, contexto: q.contexto, jung: a.jung, eixo: a.eixo,
      capacidades: parse<Capacidade>(par[0]),
      belbin: parse<PapelBelbin>(par[1])
    };
  })
);

export const LINHA_POR_ALTERNATIVA: Record<string, LinhaMatriz> =
  Object.fromEntries(MATRIZ_PONTUACAO.map(l => [l.alternativaId, l]));

/**
 * Máximo teórico por capacidade e por papel: soma, sobre todas as questões, do
 * MAIOR valor obtenível naquela questão (peso do item × maior peso da célula).
 * É o denominador correto para converter contagem bruta em escore relativo
 * interno de 0 a 100 — um respondente que maximizasse deliberadamente uma
 * capacidade atingiria exatamente 100 nela.
 */
function maximos<K extends string>(campo: 'capacidades' | 'belbin', chaves: readonly K[]) {
  const max = Object.fromEntries(chaves.map(k => [k, 0])) as Record<K, number>;
  for (const q of QUESTOES) {
    for (const k of chaves) {
      const melhor = Math.max(0, ...q.alternativas.map(a => (LINHA_POR_ALTERNATIVA[a.id][campo] as any)[k] ?? 0));
      max[k] += melhor * q.peso;
    }
  }
  return max;
}

